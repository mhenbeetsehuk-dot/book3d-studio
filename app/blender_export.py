def _scene_payload(scene: Scene) -> dict:
    return scene.model_dump()


def blender_script(project: Project) -> str:
    """Compatibility exporter: builds the first scene as an animated preview."""
    if not project.scenes:
        return '# Book3D Studio: project has no scenes\n'
    return blender_scene_script(project, project.scenes[0], "preview.mp4")


